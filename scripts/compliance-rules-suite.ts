import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { selectRules, type ComplianceRule } from "../src/lib/compliance/rules";
import { parseSubmission } from "../src/lib/compliance/service";
import { checkSubmission } from "../src/lib/compliance/checks";
const s = parseSubmission(JSON.parse(readFileSync("docs/contracts/examples/compliance-valid.json", "utf8")));
const now = "2026-10-17T00:00:00.000Z";
const types = ["advertising_law", "consumer_protection", "copyright", "ethics", "platform", "brand"] as const;
// Synthetic fixtures, never production legal guidance.
const rules: ComplianceRule[] = types.map(type => ({ id: type, source: "test-only", version: "1", type, jurisdiction: "AU", effectiveDate: "2026-01-01", expiresAt: "2026-12-31", platforms: type === "platform" ? ["web"] : [], category: type === "ethics" ? "inappropriate_content" : type === "copyright" ? "copyright" : "brand_guideline", mode: "forbidden_phrase", terms: ["test-prohibited"], reason: "Fixture rule breach", correction: "Remove fixture wording", severity: "medium", conflictsWith: [] }));
const registry = { authorisedSources: ["test-only"], rules };
const selection = selectRules(registry, s, now);
assert.equal(selection.problems.length, 0);
assert.equal(selection.referenceRules?.length ?? 0, 0);
assert.ok(selectRules(null, s, now).problems.length);
assert.ok(selectRules({ ...registry, authorisedSources: [] }, s, now).problems.some(p => p.includes("Unauthorised")));
assert.ok(selectRules(registry, s, "2027-01-01T00:00:00Z").problems.some(p => p.includes("Outdated")));
assert.ok(selectRules({ ...registry, rules: [...rules, rules[0]] }, s, now).problems.some(p => p.includes("Conflicting")));
assert.ok(selectRules({ ...registry, rules: rules.map(r => ({ ...r, conflictsWith: ["brand"] })) }, s, now).problems.some(p => p.includes("Conflicting")));
assert.ok(selectRules(registry, { ...s, country: "NZ" }, now).problems.length);
assert.ok(selectRules(registry, { ...s, targetPlatforms: ["instagram"] }, now).problems.some(p => p.includes("instagram")));
assert.equal(selectRules({ ...registry, rules: rules.map(r => ({ ...r, audiencePattern: "children" })) }, s, now).rules.length, 0);
const foreignOnly = { ...registry, rules: rules.map(r => ({ ...r, jurisdiction: "NZ" })) };
const foreignSelection = selectRules(foreignOnly, s, now);
assert.equal(foreignSelection.rules.length, 0);
assert.ok(foreignSelection.referenceRules?.some(r => r.type === "advertising_law"));
assert.ok(foreignSelection.problems.some(p => p.includes("non-binding context")));
const original = JSON.stringify(s);
const checked = checkSubmission(s, selection);
assert.equal(JSON.stringify(s), original);
assert.ok(checked.issues.some(i => i.category === "unsupported_claim"));
const risky = structuredClone(s);
risky.targetAudience = "children";
risky.content[0] = { ...risky.content[0], headline: "test-prohibited guaranteed", body: "Free offer $30", imageUrl: "https://example.invalid/asset.png" };
const result = checkSubmission(risky, selection);
for (const category of ["unsupported_claim", "missing_condition", "price_accuracy", "copyright", "audience_targeting", "inappropriate_content"])
  assert.ok(result.issues.some(i => i.category === category), category);
assert.ok(result.issues.filter(i => i.basis === "confirmed_breach").every(i => i.policySource === "test-only" || i.rule === "retailer.banned-terms"));
const clean = structuredClone(s);
clean.brandAssets.bannedTerms = [];
clean.content = clean.content.map(c => ({ ...c, headline: "Cotton shirt", body: "Available in store", caption: "Everyday wear", callToAction: "Browse" }));
assert.equal(checkSubmission(clean, selection).issues.length, 0);
const required = { ...rules[0], mode: "required_phrase" as const, terms: ["conditions apply"] };
assert.ok(checkSubmission(clean, { ...selection, rules: [required] }).issues.some(i => i.basis === "confirmed_breach"));
console.log("PASS CC-03/04: source authorisation, coverage, dates, conflicts, jurisdiction/platform/audience selection, content categories, immutable inputs and clean/violating cases.");
