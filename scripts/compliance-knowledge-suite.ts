import assert from "node:assert/strict";
import { mkdtempSync, writeFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { KnowledgeStore, extractPassages } from "../src/lib/compliance/knowledge/store";
const dir = mkdtempSync(join(tmpdir(), "aisle-kb-"));
const file = join(dir, "policy.md");
const db = join(dir, "knowledge.db");
const sourceUrl = "https://example.invalid/synthetic-policy";
const metadata = { documentId: "fixture", title: "Synthetic test policy", publisher: "Test only", sourceUrl, version: "1", jurisdiction: "AU", kind: "brand_policy", platforms: ["web"], effectiveFrom: "2026-01-01", effectiveTo: null, downloadedAt: "2026-10-01T00:00:00Z", checkedAt: "2026-10-01T00:00:00Z", reviewAfter: "2026-12-01" };
const options = { jurisdiction: "AU", authorisedSources: [sourceUrl], platform: "web", now: "2026-10-18T00:00:00Z" };
let store = new KnowledgeStore(db);
try {
  writeFileSync(file, "# Promotion\nSynthetic discount conditions must be stated.\n");
  await assert.rejects(store.ingest(file, metadata, []), /allow-list/);
  assert.equal(store.list().length, 0);
  const first = await store.ingest(file, metadata, [sourceUrl]);
  assert.equal((await store.ingest(file, metadata, [sourceUrl])).duplicate, true);
  const result = store.search("discount", options);
  assert.equal(result.passages.length, 1);
  assert.match(result.passages[0].location, /Promotion; line 2/);
  assert.equal(result.passages[0].document.revisionId, first.revisionId);
  assert.equal(store.search("discount", { ...options, jurisdiction: "NZ" }).passages.length, 0);
  assert.equal(store.search("discount", { ...options, platform: "email" }).passages.length, 0);
  assert.equal(store.search("discount", { ...options, authorisedSources: [] }).passages.length, 0);
  assert.equal(store.search("discount", { ...options, now: "2027-01-01T00:00:00Z" }).passages.length, 0);
  assert.ok(store.search("zzzzzz", options).problems.length);
  assert.doesNotThrow(() => store.search('" OR * ( discount', options));
  writeFileSync(file, "Replacement policy about refunds.");
  await assert.rejects(store.ingest(file, metadata, [sourceUrl]), /immutable/);
  assert.equal(store.search("discount", options).passages.length, 1);
  await store.ingest(file, { ...metadata, version: "2" }, [sourceUrl]);
  assert.equal(store.list().length, 2);
  assert.equal(store.list().filter(d => d.active).length, 1);
  assert.equal(store.search("discount", options).passages.length, 0);
  assert.equal(store.search("refunds", options).passages.length, 1);
  store.close(); store = new KnowledgeStore(db);
  assert.equal(store.search("refunds", options).passages.length, 1);
  await store.ingest(file, { ...metadata, documentId: "undated", effectiveFrom: null }, [sourceUrl]);
  assert.ok(store.search("refunds", options).problems.some(p => p.includes("unknown")));
  await assert.rejects(extractPassages(new Uint8Array(), ".txt"), /no searchable/);
  await assert.rejects(extractPassages(new Uint8Array(), ".html"), /Supported formats/);
  const long = await extractPassages(new TextEncoder().encode("x".repeat(3200)), ".txt");
  assert.equal(long.length, 3);
  assert.ok(long.every(p => p.text.length <= 1600));
  console.log("PASS: authorisation, immutable versions, citations, active revisions, persistence, scoped retrieval, freshness, unknown dates, safe queries and extraction limits.");
} finally { store.close(); rmSync(dir, { recursive: true, force: true }); }
